// ---- tracking (ported from finger-frame-effect main.js) ----
function toPixel(lm) {
  return { x: lm.x * canvas.width, y: lm.y * canvas.height };
}
function dist(a, b) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}
function lerpPt(a, b, t) {
  return { x: a.x + (b.x - a.x) * t, y: a.y + (b.y - a.y) * t };
}
function polygonArea(pts) {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const p = pts[i], q = pts[(i + 1) % pts.length];
    a += p.x * q.y - q.x * p.y;
  }
  return Math.abs(a / 2);
}

// A band is a pair of adjacent fingertips; both hands' pairs form the quad
// [A.hi, B.hi, B.lo, A.lo], each hand contributing one edge — the same
// construction as the original thumb–index frame. Spread/area gates are
// fractions of the hand scale (wrist→middle-MCP) and the canvas area;
// non-thumb gaps are anatomically far smaller when fully spread, so their
// thresholds sit much lower.
const SINGLE_BAND = {
  lo: THUMB_TIP, hi: INDEX_TIP,
  acquire: 0.75, keep: 0.2, areaAcquire: 0.005, areaKeep: 0.0005,
};
const MULTI_BANDS = [
  SINGLE_BAND,
  { lo: INDEX_TIP, hi: MIDDLE_TIP, acquire: 0.28, keep: 0.09, areaAcquire: 0.002, areaKeep: 0.0003 },
  { lo: MIDDLE_TIP, hi: RING_TIP, acquire: 0.24, keep: 0.08, areaAcquire: 0.002, areaKeep: 0.0003 },
  { lo: RING_TIP, hi: PINKY_TIP, acquire: 0.26, keep: 0.08, areaAcquire: 0.002, areaKeep: 0.0003 },
];

class QuadTracker {
  constructor(band) {
    this.band = band;
    this.reset();
  }

  reset() {
    this.corners = null;
    this.presence = 0;
    this.frameActive = false;
    this.lostFrames = 0;
    this.jumpFrames = 0;
  }

  get visible() {
    return !!this.corners && this.presence > 0.01;
  }

  computeQuad(hands) {
    if (hands.length !== 2) return null;
    const info = hands.map((lm) => ({
      hi: toPixel(lm[this.band.hi]),
      lo: toPixel(lm[this.band.lo]),
      wristX: toPixel(lm[WRIST]).x,
      scale: dist(toPixel(lm[WRIST]), toPixel(lm[MIDDLE_MCP])) + 1,
    }));
    const needed = this.frameActive ? this.band.keep : this.band.acquire;
    for (const hd of info) {
      if (dist(hd.lo, hd.hi) < hd.scale * needed) return null;
    }
    info.sort((a, b) => a.wristX - b.wristX);
    const [A, B] = info;
    const pts = [A.hi, B.hi, B.lo, A.lo];
    const cx = pts.reduce((s, p) => s + p.x, 0) / 4;
    const cy = pts.reduce((s, p) => s + p.y, 0) / 4;
    const hull = [...pts].sort(
      (a, b) => Math.atan2(a.y - cy, a.x - cx) - Math.atan2(b.y - cy, b.x - cx)
    );
    const minArea = this.frameActive ? this.band.areaKeep : this.band.areaAcquire;
    if (polygonArea(hull) < canvas.width * canvas.height * minArea) return null;
    return pts;
  }

  update(hands) {
    const target = this.computeQuad(hands);
    if (target) {
      if (!this.corners) {
        this.lostFrames = 0;
        this.frameActive = true;
        this.jumpFrames = 0;
        this.corners = target;
        this.presence = Math.min(1, this.presence + 0.12);
      } else {
        const moved =
          target.reduce((s, p, i) => s + dist(p, this.corners[i]), 0) / 4;
        if (moved > canvas.width * 0.3 && ++this.jumpFrames < JUMP_CONFIRM_FRAMES) {
          if (++this.lostFrames > MAX_LOST_FRAMES)
            this.presence = Math.max(0, this.presence - 0.05);
        } else {
          this.lostFrames = 0;
          this.frameActive = true;
          this.jumpFrames = 0;
          const alpha = Math.min(0.85, Math.max(0.35, moved / (canvas.width * 0.05)));
          this.corners = this.corners.map((c, i) => lerpPt(c, target[i], alpha));
          this.presence = Math.min(1, this.presence + 0.12);
        }
      }
    } else if (this.corners && ++this.lostFrames <= MAX_LOST_FRAMES) {
      this.presence = Math.min(1, this.presence + 0.12);
    } else {
      this.presence = Math.max(0, this.presence - 0.05);
      if (this.presence === 0) {
        this.corners = null;
        this.frameActive = false;
        this.jumpFrames = 0;
      }
    }
  }
}

