  new Promise((resolve) => {
    orig.onseeked = () => {
      orig.onseeked = null;
      if (!landmarker) return resolve(null); // tracker still loading
      ctx.drawImage(orig, 0, 0, canvas.width, canvas.height);
      const res = landmarker.detectForVideo(orig, performance.now());
      const hands = res.landmarks || [];
      for (const tk of trackers) tk.update(hands);
      for (const tk of trackers) {
        if (tk.visible) {
          drawWindow(tk.corners, tk.presence);
          drawOutline(tk.corners, t, tk.presence);
        }
      }
      const primary = trackers[0];
      resolve({
        presence: +primary.presence.toFixed(2),
        corners: primary.corners
          ? primary.corners.map((p) => [Math.round(p.x), Math.round(p.y)])
          : null,
        quads: trackers
          .filter((tk) => tk.visible)
          .map((tk) => tk.corners.map((p) => [Math.round(p.x), Math.round(p.y)])),
      });
    };
    orig.currentTime = t;
  });

